async page => {
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Network.clearBrowserCache');
  await cdp.detach();
  await page.goto(page.url());
  await page.setViewportSize({width: 1440, height: 1000});
  await page.locator('#status').filter({hasText: 'asset-001 selected'}).waitFor();
  await page.getByRole('button', {name: 'Mark inspected', exact: true}).click();
  await page.locator('#status').filter({hasText: '1 inspected'}).waitFor();
  await page.getByRole('spinbutton', {name: 'Downtime threshold'}).fill('70');
  await page.getByRole('button', {name: 'Apply', exact: true}).click();
  await page.locator('#record').filter({hasText: '70'}).waitFor();
  await page.getByRole('button', {name: 'Expand North', exact: true}).click();
  await page.locator('#sites').getByText('asset-005', {exact: true}).click();
  await page.locator('#status').filter({hasText: 'asset-005 selected'}).waitFor();
  await page.locator('#find input').fill('asset-015');
  await page.locator('#find input').press('Enter');
  await page.locator('#status').filter({hasText: 'asset-015 selected'}).waitFor();
  const results = await page.evaluate(async () => {
    const transport = window.ShinyCapabilitiesDirectTransport;
    const before = transport.diagnostics();
    const grid = document.getElementById('equipment');
    const parent = grid.parentElement, next = grid.nextSibling;
    const temporary = document.createElement('div'); parent.appendChild(temporary);
    temporary.appendChild(grid);
    await new Promise(resolve => setTimeout(resolve, 100));
    parent.insertBefore(grid, next); temporary.remove();
    await new Promise(resolve => setTimeout(resolve, 100));
    const after = transport.diagnostics();
    if (after.destroys !== before.destroys) throw new Error('DOM move destroyed a live component');
    if (!grid.querySelector('.ag-root')) throw new Error('Grid disappeared after reparenting');
    grid.style.display = 'none';
    await new Promise(resolve => setTimeout(resolve, 100));
    grid.style.display = '';
    const host = document.createElement('div'); document.body.appendChild(host);
    host.innerHTML = '<div id="late-static" class="sc-direct-component-output" style="height:200px" data-sc-direct-component="object_inspector"><script type="application/json" data-sc-direct-payload="late-static">{"component":"object_inspector","payload":{"value":{"sample":1}},"revision":1}</script></div>';
    await new Promise(resolve => setTimeout(resolve, 250));
    const mounted = transport.diagnostics();
    if (mounted.liveInstances !== after.liveInstances + 1) throw new Error('Late insertion did not mount');
    host.remove();
    await new Promise(resolve => setTimeout(resolve, 100));
    if (transport.diagnostics().liveInstances !== after.liveInstances) throw new Error('Late insertion leaked');
    return {before, after: transport.diagnostics(), gridRowsInDOM: grid.querySelectorAll('.ag-row').length};
  });
  console.log(JSON.stringify(results));
  await page.screenshot({path: 'sc-equipment-desktop.png', fullPage: true});
  await page.setViewportSize({width: 900, height: 1100});
  await page.waitForTimeout(1500);
  await page.screenshot({path: 'sc-equipment-900.png', fullPage: true});
  console.log('COMPOSITION_BROWSER_PASS');
}
